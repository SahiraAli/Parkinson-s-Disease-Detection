    print(f"\n========== Fold {fold+1} ==========")

    X_train, X_test = X[train_idx], X[test_idx]
    y_train, y_test = y[train_idx], y[test_idx]

    model = build_lstm_model(input_shape=(X_train.shape[1], X_train.shape[2]))
    history = model.fit(X_train, y_train, validation_data=(X_test, y_test), epochs=30, batch_size=32, verbose=0)

    # Final Training Evaluation
    y_pred_train = (model.predict(X_train) > 0.5).astype(int)
    y_pred_test = (model.predict(X_test) > 0.5).astype(int)
    y_prob_test = model.predict(X_test).ravel()

    train_acc_fold = accuracy_score(y_train, y_pred_train)
    test_acc_fold = accuracy_score(y_test, y_pred_test)

    train_loss_fold = log_loss(y_train, model.predict(X_train).ravel())
    test_loss_fold = log_loss(y_test, y_prob_test)

    fold_train_accs.append(train_acc_fold)
    fold_test_accs.append(test_acc_fold)
    fold_train_losses.append(train_loss_fold)
    fold_test_losses.append(test_loss_fold)

    roc_probs.extend(y_prob_test)
    roc_labels.extend(y_test)

