from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Dropout

# Load dataset
df = pd.read_csv("/content/pd_speech_features.csv")
label_encoder = LabelEncoder()
y = label_encoder.fit_transform(df['class'])
X = df.drop(['class'], axis=1)

# Standardize
scaler = StandardScaler()
X = scaler.fit_transform(X)

# Reshape for LSTM
X = X.reshape(X.shape[0], 1, X.shape[1])

def build_lstm_model(input_shape):
    model = Sequential([
        LSTM(64, return_sequences=True, input_shape=input_shape),
        Dropout(0.2),
        LSTM(32, return_sequences=False),
        Dropout(0.2),
        Dense(32, activation='relu'),
        Dense(1, activation='sigmoid')
    ])
    model.compile(loss='binary_crossentropy', optimizer='adam', metrics=['accuracy'])
    return model

kf = StratifiedKFold(n_splits=5, shuffle=True, random_state=45)

# Trackers
train_accs = []          # Training accuracy per epoch
train_losses = []        # Training loss per epoch
fold_train_accs = []     # Training accuracy after each fold
fold_test_accs = []      # Testing accuracy after each fold
acc_scores = []          # Accuracy on test per fold
precision_scores = []    # Precision per fold
recall_scores = []       # Recall per fold
f1_scores = []           # F1 per fold
roc_probs = []           # Probabilities for ROC
roc_labels = []          # True labels for ROC

for fold, (train_idx, test_idx) in enumerate(kf.split(X, y)):
    print(f"\n========== Fold {fold+1} ==========")

    X_train, X_test = X[train_idx], X[test_idx]
    y_train, y_test = y[train_idx], y[test_idx]

    model = build_lstm_model(input_shape=(X_train.shape[1], X_train.shape[2]))
    history = model.fit(X_train, y_train, epochs=30, batch_size=32, verbose=0)

    # Collect training acc/loss per epoch
    train_accs.extend(history.history['accuracy'])
    train_losses.extend(history.history['loss'])

    # Final fold evaluation
    y_pred_train = (model.predict(X_train) > 0.5).astype(int)
    y_pred_test = (model.predict(X_test) > 0.5).astype(int)
    y_prob_test = model.predict(X_test).ravel()

    train_acc_fold = accuracy_score(y_train, y_pred_train)
    test_acc_fold = accuracy_score(y_test, y_pred_test)

    fold_train_accs.append(train_acc_fold)
    fold_test_accs.append(test_acc_fold)

    acc_scores.append(test_acc_fold)
    precision_scores.append(precision_score(y_test, y_pred_test))
    recall_scores.append(recall_score(y_test, y_pred_test))
    f1_scores.append(f1_score(y_test, y_pred_test))

    roc_probs.extend(y_prob_test)
    roc_labels.extend(y_test)

